-- ===============================================================
-- 1. COMPONENTE GEOGRÁFICO Y TABLAS AUXILIARES
--    Rescatado desde REGION, COMUNA, PAIS, UNIDAD y PARAMETRO.
-- ===============================================================

CREATE TABLE region (
    id_region INTEGER PRIMARY KEY,
    nombre_region VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE pais (
    id_pais INTEGER PRIMARY KEY,
    nombre_pais VARCHAR(120) NOT NULL UNIQUE,
    codigo_iso3 CHAR(3) NOT NULL UNIQUE
);

CREATE TABLE comuna (
    id_comuna INTEGER PRIMARY KEY,
    nombre_comuna VARCHAR(80) NOT NULL,
    id_region INTEGER NOT NULL REFERENCES region(id_region),
    UNIQUE (nombre_comuna, id_region)
);

CREATE TABLE unidad (
    id_unidad INTEGER PRIMARY KEY,
    nombre_unidad VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE parametro (
    id_parametro INTEGER PRIMARY KEY,
    nombre_parametro VARCHAR(60) NOT NULL UNIQUE,
    valor_numerico NUMERIC(12,2),
    valor_texto VARCHAR(200),
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo'
);

CREATE TABLE estado_pedido (
    id_estado_pedido INTEGER PRIMARY KEY,
    nombre_estado VARCHAR(40) NOT NULL UNIQUE,
    descripcion TEXT,
    orden INTEGER NOT NULL
);

-- ===============================================================
-- 2. COMPONENTE DE SEGURIDAD, ROLES, PERMISOS Y USUARIOS
--    Adapta PERFIL/USUARIA del modelo original hacia RBAC simple.
-- ===============================================================

CREATE TABLE rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permiso (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_permiso VARCHAR(100) NOT NULL UNIQUE,
    modulo VARCHAR(80) NOT NULL,
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo'
);

CREATE TABLE rol_permiso (
    id_rol INTEGER NOT NULL REFERENCES rol(id_rol) ON DELETE CASCADE,
    id_permiso INTEGER NOT NULL REFERENCES permiso(id_permiso) ON DELETE CASCADE,
    PRIMARY KEY (id_rol, id_permiso)
);

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100),
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    telefono VARCHAR(30),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    ultimo_acceso TIMESTAMP,
    id_rol INTEGER NOT NULL REFERENCES rol(id_rol),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===============================================================
-- 3. COMPONENTE CLIENTES Y EVENTOS
--    Adapta CLIENTA y REP_LEGAL; agrega EVENTO requerido por el proyecto.
-- ===============================================================

CREATE TABLE representante_legal (
    id_representante_legal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut VARCHAR(20),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100),
    email VARCHAR(150),
    telefono VARCHAR(30),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo'
);

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut VARCHAR(20),
    tipo_cliente VARCHAR(40) NOT NULL DEFAULT 'persona_natural',
    nombre VARCHAR(150) NOT NULL,
    apellido VARCHAR(100),
    nombre_fantasia VARCHAR(150),
    giro VARCHAR(200),
    email VARCHAR(150),
    telefono VARCHAR(30),
    direccion TEXT,
    id_comuna INTEGER REFERENCES comuna(id_comuna),
    id_pais INTEGER REFERENCES pais(id_pais),
    id_representante_legal INTEGER REFERENCES representante_legal(id_representante_legal),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE evento (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_evento VARCHAR(150) NOT NULL,
    fecha_evento DATE NOT NULL,
    hora_evento TIME,
    direccion TEXT NOT NULL,
    cantidad_personas INTEGER CHECK (cantidad_personas IS NULL OR cantidad_personas > 0),
    observaciones TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'planificado',
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_cliente),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===============================================================
-- 4. COMPONENTE PEDIDOS Y TRAZABILIDAD
--    Adapta PEDIDO, DETALLE_PEDIDO y ESTADO_PEDIDO.
-- ===============================================================

CREATE TABLE pedido (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_pedido VARCHAR(30) NOT NULL UNIQUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_compromiso DATE,
    fecha_entrega DATE,
    observaciones TEXT,
    costo_estimado NUMERIC(12,2) NOT NULL DEFAULT 0,
    margen_objetivo NUMERIC(5,2) NOT NULL DEFAULT 0,
    precio_estimado NUMERIC(12,2) NOT NULL DEFAULT 0,
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_cliente),
    id_evento INTEGER REFERENCES evento(id_evento),
    id_estado_pedido INTEGER NOT NULL REFERENCES estado_pedido(id_estado_pedido),
    id_usuario_responsable INTEGER REFERENCES usuario(id_usuario),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE historial_pedido (
    id_historial_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedido(id_pedido) ON DELETE CASCADE,
    id_estado_anterior INTEGER REFERENCES estado_pedido(id_estado_pedido),
    id_estado_nuevo INTEGER NOT NULL REFERENCES estado_pedido(id_estado_pedido),
    observacion TEXT,
    id_usuario INTEGER REFERENCES usuario(id_usuario),
    fecha_cambio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===============================================================
-- 5. COMPONENTE PRODUCCIÓN: PROVEEDORES, INSUMOS, FICHAS Y RECETAS
--    Adapta PROVEEDORA, ITEM, FT, DETALLE_INGREDIENTE y DETALLE_PREPARACION.
-- ===============================================================

CREATE TABLE proveedor (
    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_proveedor VARCHAR(150) NOT NULL,
    rut VARCHAR(20),
    nombre_contacto VARCHAR(100),
    email VARCHAR(150),
    telefono VARCHAR(30),
    direccion TEXT,
    id_comuna INTEGER REFERENCES comuna(id_comuna),
    id_pais INTEGER REFERENCES pais(id_pais),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE insumo (
    id_insumo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_insumo VARCHAR(150) NOT NULL,
    descripcion TEXT,
    categoria VARCHAR(60),
    id_unidad INTEGER NOT NULL REFERENCES unidad(id_unidad),
    costo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    stock_minimo NUMERIC(12,3) NOT NULL DEFAULT 0,
    codigo_qr VARCHAR(120) UNIQUE,
    id_proveedor INTEGER REFERENCES proveedor(id_proveedor),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ficha_tecnica (
    id_ficha_tecnica INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_ficha VARCHAR(150) NOT NULL,
    descripcion TEXT,
    tipo_preparacion VARCHAR(80),
    rendimiento NUMERIC(12,3) NOT NULL DEFAULT 1,
    id_unidad_rendimiento INTEGER REFERENCES unidad(id_unidad),
    costo_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    precio_sugerido NUMERIC(12,2) NOT NULL DEFAULT 0,
    margen_objetivo NUMERIC(5,2) NOT NULL DEFAULT 0,
    imagen_url TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE receta (
    id_receta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ficha_tecnica INTEGER NOT NULL REFERENCES ficha_tecnica(id_ficha_tecnica) ON DELETE CASCADE,
    id_insumo INTEGER NOT NULL REFERENCES insumo(id_insumo),
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
    id_unidad INTEGER NOT NULL REFERENCES unidad(id_unidad),
    costo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    costo_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    observacion TEXT,
    UNIQUE (id_ficha_tecnica, id_insumo)
);

CREATE TABLE detalle_preparacion (
    id_detalle_preparacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ficha_tecnica INTEGER NOT NULL REFERENCES ficha_tecnica(id_ficha_tecnica) ON DELETE CASCADE,
    orden INTEGER NOT NULL DEFAULT 1,
    instruccion TEXT NOT NULL
);

CREATE TABLE detalle_pedido (
    id_detalle_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedido(id_pedido) ON DELETE CASCADE,
    tipo_detalle VARCHAR(30) NOT NULL DEFAULT 'ficha_tecnica',
    id_ficha_tecnica INTEGER REFERENCES ficha_tecnica(id_ficha_tecnica),
    id_insumo INTEGER REFERENCES insumo(id_insumo),
    descripcion_manual VARCHAR(200),
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    precio_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    subtotal NUMERIC(12,2) GENERATED ALWAYS AS (ROUND((cantidad * precio_unitario)::numeric, 2)) STORED,
    CHECK (
        id_ficha_tecnica IS NOT NULL
        OR id_insumo IS NOT NULL
        OR descripcion_manual IS NOT NULL
    )
);

-- ===============================================================
-- 6. COMPONENTE COTIZACIÓN AUTOMÁTICA DE COSTOS Y MARGEN
-- ===============================================================

CREATE TABLE cotizacion (
    id_cotizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedido(id_pedido) ON DELETE CASCADE,
    fecha_cotizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    costo_insumos NUMERIC(12,2) NOT NULL DEFAULT 0,
    costo_personal NUMERIC(12,2) NOT NULL DEFAULT 0,
    costo_transporte NUMERIC(12,2) NOT NULL DEFAULT 0,
    otros_costos NUMERIC(12,2) NOT NULL DEFAULT 0,
    costo_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    margen_objetivo NUMERIC(5,2) NOT NULL DEFAULT 0,
    precio_sugerido NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado VARCHAR(30) NOT NULL DEFAULT 'vigente',
    observacion TEXT,
    id_usuario INTEGER REFERENCES usuario(id_usuario)
);

-- ===============================================================
-- 7. COMPONENTE INVENTARIO, BODEGAS, QR Y MOVIMIENTOS
--    Reemplaza ENTRADA/SALIDA por MOVIMIENTO_INVENTARIO.
-- ===============================================================

CREATE TABLE bodega (
    id_bodega INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_bodega VARCHAR(150) NOT NULL,
    direccion TEXT,
    tipo_bodega VARCHAR(60),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo'
);

CREATE TABLE inventario (
    id_inventario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_insumo INTEGER NOT NULL REFERENCES insumo(id_insumo),
    id_bodega INTEGER NOT NULL REFERENCES bodega(id_bodega),
    stock_actual NUMERIC(12,3) NOT NULL DEFAULT 0,
    stock_minimo NUMERIC(12,3) NOT NULL DEFAULT 0,
    ubicacion VARCHAR(150),
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    UNIQUE (id_insumo, id_bodega)
);

CREATE TABLE movimiento_inventario (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimiento VARCHAR(30) NOT NULL CHECK (tipo_movimiento IN ('entrada', 'salida', 'consumo', 'ajuste')),
    fecha_movimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    observacion TEXT,
    id_insumo INTEGER NOT NULL REFERENCES insumo(id_insumo),
    id_bodega INTEGER NOT NULL REFERENCES bodega(id_bodega),
    id_pedido INTEGER REFERENCES pedido(id_pedido),
    id_usuario INTEGER REFERENCES usuario(id_usuario)
);

-- ===============================================================
-- 8. COMPONENTE VENTAS, FACTURACIÓN INTERNA Y PAGOS
--    No integra SII; registra facturación interna para MVP.
-- ===============================================================

CREATE TABLE venta (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedido(id_pedido),
    fecha_venta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado VARCHAR(30) NOT NULL DEFAULT 'registrada',
    observacion TEXT
);

CREATE TABLE factura (
    id_factura INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta INTEGER NOT NULL REFERENCES venta(id_venta) ON DELETE CASCADE,
    numero_factura VARCHAR(50),
    fecha_emision DATE NOT NULL DEFAULT CURRENT_DATE,
    monto_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado VARCHAR(30) NOT NULL DEFAULT 'emitida',
    observacion TEXT
);

CREATE TABLE pago (
    id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura INTEGER NOT NULL REFERENCES factura(id_factura) ON DELETE CASCADE,
    fecha_pago DATE NOT NULL DEFAULT CURRENT_DATE,
    monto NUMERIC(12,2) NOT NULL CHECK (monto >= 0),
    metodo_pago VARCHAR(50),
    estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
    observacion TEXT
);

-- ===============================================================
